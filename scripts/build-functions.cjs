'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const acorn = require('acorn');
const root = path.resolve(__dirname, '..');
const file = path.join(root, 'functions/index.js');
const source = fs.readFileSync(file, 'utf8');
const core = new Set(['applyHospitalPolicy', 'issueHospitalCertificate', 'syncStaffUid', 'syncStaffProfile', 'publishQueueDisplay', 'publishHospitalDisplay', 'refreshPublicDisplays', 'setPatientPortalPin', 'getPatientPortalData']);
const ast = acorn.parse(source, { ecmaVersion: 'latest', sourceType: 'script' });
const cuts = [];
const exported = [];
for (const node of ast.body) {
    if (node.type === 'VariableDeclaration' && node.declarations.some(declaration => declaration.init && declaration.init.type === 'CallExpression' && declaration.init.callee.name === 'defineSecret')) {
        cuts.push([node.start, node.end]);
    }
    if (node.type !== 'ExpressionStatement' || node.expression.type !== 'AssignmentExpression') continue;
    const left = node.expression.left;
    if (left.type !== 'MemberExpression' || left.object.name !== 'exports') continue;
    const name = left.property.name;
    if (core.has(name)) exported.push(name);
    else cuts.push([node.start, node.end]);
}
if (exported.length !== core.size) throw new Error('Core function export set is incomplete.');
let built = source;
for (const [start, end] of cuts.sort((a, b) => b[0] - a[0])) built = built.slice(0, start) + built.slice(end);
built = '// Generated by scripts/build-functions.cjs; edit functions/index.js.\n' + built;
new vm.Script(built, { filename: 'functions/core.cjs' });
fs.writeFileSync(path.join(root, 'functions/core.cjs'), built);
fs.copyFileSync(path.join(root, 'js/hospital-policy.js'), path.join(root, 'functions/hospital-policy.cjs'));
console.log('Built nine core functions without optional provider secrets.');
