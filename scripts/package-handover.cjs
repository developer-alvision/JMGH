'use strict';
/*
 * Builds the client handover archive.
 *
 * What goes in: every source file, the server functions, the security rules
 * and indexes, the scripts, the tests and the handbook. What stays out:
 * anything installed (node_modules, the bundled JRE), anything generated
 * (dist, emulator state, logs), and anything that could carry a credential or
 * tie the archive to a developer's account.
 *
 * The exclusion list is deliberately a denylist of local-only artefacts rather
 * than an allowlist of files, because a missed source file breaks the app
 * loudly while a missed artefact only makes the archive bigger. The one
 * exception is the credential patterns, which are checked by name AND by
 * content before anything is written: see scanForSecrets below.
 */
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');

const root = path.resolve(__dirname, '..');
const stamp = new Date().toISOString().slice(0, 10);
// Everything the client is sent lands in handover/: this archive plus the
// handbook and covering letter as Word documents. The handbook is kept
// alongside the archive rather than inside it, so it can be read and sent on
// without anyone having to unzip the system first.
const outDir = path.join(root, 'handover');
const zipFile = path.join(outDir, `jmgh-hms-handover-${stamp}.zip`);

// Directories never included, matched on the path relative to the root.
const SKIP_DIRS = new Set([
  'node_modules',          // reinstalled with npm install
  'functions/node_modules',
  '.runtime',              // bundled JRE, ~180 MB, re-fetched by npm run setup:java
  '.emulator-data',        // local emulator state
  '.firebase',             // hosting deploy cache, holds the last project id
  '.vercel',               // links the folder to a hosting account
  'dist',                  // generated by npm run build
  'test-results',          // local test output
  '.claude',               // local tool settings
  '.git',
  'handover',              // the output folder itself — never nest it
  'docs'                   // the handbook travels beside the zip, not in it
]);

// Individual files never included.
const SKIP_FILES = new Set([
  'functions/.secret.local'
]);

// Filename patterns that must never appear in a handover archive.
const SKIP_PATTERNS = [
  /(^|\/)\.env/i,                     // .env, .env.local — deployment tokens
  /service[-_.]?account.*\.json$/i,   // Firebase Admin private keys
  /\.pem$/i,
  /\.p12$/i,
  /\.key$/i,
  /-debug\.log/i,
  /\.log$/i,
  /\.zip$/i                           // never nest a previous archive
];

// Content patterns checked in every text file actually being packaged. These
// are the shapes a real credential takes; a hit aborts the build rather than
// shipping it. Demo and emulator values are allowed through by name.
const SECRET_PATTERNS = [
  [/AIza[0-9A-Za-z_-]{30,}/, 'Google API key'],
  [/-----BEGIN [A-Z ]*PRIVATE KEY-----/, 'private key block'],
  [/\bprj_[A-Za-z0-9]{20,}\b/, 'hosting project identifier'],
  [/\bteam_[A-Za-z0-9]{20,}\b/, 'hosting team identifier'],
  [/\beyJ[A-Za-z0-9_-]{30,}\.[A-Za-z0-9_-]{20,}\./, 'JWT / OIDC token'],
  [/\bghp_[A-Za-z0-9]{30,}\b/, 'GitHub token'],
  [/\bsk_live_[A-Za-z0-9]{20,}\b/, 'live payment secret key'],
  [/\brzp_live_[A-Za-z0-9]{10,}\b/, 'live Razorpay key']
];
const TEXT_EXTENSIONS = new Set(['.js', '.cjs', '.mjs', '.json', '.html', '.css', '.md', '.txt', '.rules', '.webmanifest', '.yml', '.yaml']);

function skipped(rel, isDir) {
  if (isDir) return SKIP_DIRS.has(rel);
  if (SKIP_FILES.has(rel)) return true;
  return SKIP_PATTERNS.some(pattern => pattern.test(rel));
}

const entries = [];
(function collect(dir, prefix) {
  for (const item of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const rel = (prefix ? prefix + '/' : '') + item.name;
    if (skipped(rel, item.isDirectory())) continue;
    if (item.isDirectory()) collect(path.join(dir, item.name), rel);
    else if (item.isFile()) entries.push({ full: path.join(dir, item.name), rel });
  }
})(root, '');

if (!entries.length) throw new Error('No files collected; refusing to write an empty archive.');

// --- credential scan, before a single byte is written ------------------------
function scanForSecrets() {
  const hits = [];
  for (const entry of entries) {
    if (!TEXT_EXTENSIONS.has(path.extname(entry.rel).toLowerCase())) continue;
    if (entry.rel.startsWith('js/jspdf') || entry.rel.startsWith('vendor/')) continue; // third-party, author emails only
    let text;
    try { text = fs.readFileSync(entry.full, 'utf8'); } catch (error) { continue; }
    for (const [pattern, label] of SECRET_PATTERNS) {
      const match = text.match(pattern);
      if (match) hits.push(`${entry.rel}: ${label} (${match[0].slice(0, 12)}…)`);
    }
  }
  return hits;
}

const hits = scanForSecrets();
if (hits.length) {
  console.error('\nRefusing to package. Credential-shaped values found:\n');
  hits.forEach(hit => console.error('  ' + hit));
  console.error('\nRemove or parameterise each one, then run this again.');
  process.exit(1);
}
console.log(`Credential scan clean across ${entries.length} files.`);

// --- write the archive (store/deflate, no external dependency) --------------
const localChunks = [];
const cdChunks = [];
let localOffset = 0;

for (const entry of entries) {
  const content = fs.readFileSync(entry.full);
  const crc = zlib.crc32(content);
  const deflated = zlib.deflateRawSync(content, { level: 9 });
  const useDeflate = deflated.length < content.length;
  const body = useDeflate ? deflated : content;
  const method = useDeflate ? 8 : 0;

  const mtime = fs.statSync(entry.full).mtime;
  const dosTime = ((mtime.getHours() << 11) | (mtime.getMinutes() << 5) | (mtime.getSeconds() >> 1)) & 0xffff;
  const dosDate = (((mtime.getFullYear() - 1980) << 9) | ((mtime.getMonth() + 1) << 5) | mtime.getDate()) & 0xffff;
  const nameBuf = Buffer.from(entry.rel, 'utf8');

  const lfh = Buffer.alloc(30);
  lfh.writeUInt32LE(0x04034b50, 0);
  lfh.writeUInt16LE(20, 4);
  lfh.writeUInt16LE(0x0800, 6);            // UTF-8 names
  lfh.writeUInt16LE(method, 8);
  lfh.writeUInt16LE(dosTime, 10);
  lfh.writeUInt16LE(dosDate, 12);
  lfh.writeUInt32LE(crc, 14);
  lfh.writeUInt32LE(body.length, 18);
  lfh.writeUInt32LE(content.length, 22);
  lfh.writeUInt16LE(nameBuf.length, 26);
  lfh.writeUInt16LE(0, 28);
  localChunks.push(lfh, nameBuf, body);

  const cdh = Buffer.alloc(46);
  cdh.writeUInt32LE(0x02014b50, 0);
  cdh.writeUInt16LE(0x0314, 4);
  cdh.writeUInt16LE(20, 6);
  cdh.writeUInt16LE(0x0800, 8);
  cdh.writeUInt16LE(method, 10);
  cdh.writeUInt16LE(dosTime, 12);
  cdh.writeUInt16LE(dosDate, 14);
  cdh.writeUInt32LE(crc, 16);
  cdh.writeUInt32LE(body.length, 20);
  cdh.writeUInt32LE(content.length, 24);
  cdh.writeUInt16LE(nameBuf.length, 28);
  cdh.writeUInt16LE(0, 30);
  cdh.writeUInt16LE(0, 32);
  cdh.writeUInt16LE(0, 34);
  cdh.writeUInt16LE(0, 36);
  cdh.writeUInt32LE((0o100644 << 16) >>> 0, 38);
  cdh.writeUInt32LE(localOffset, 42);
  cdChunks.push(cdh, nameBuf);

  localOffset += lfh.length + nameBuf.length + body.length;
}

const cdSize = cdChunks.reduce((total, buffer) => total + buffer.length, 0);
const eocd = Buffer.alloc(22);
eocd.writeUInt32LE(0x06054b50, 0);
eocd.writeUInt16LE(0, 4);
eocd.writeUInt16LE(0, 6);
eocd.writeUInt16LE(entries.length, 8);
eocd.writeUInt16LE(entries.length, 10);
eocd.writeUInt32LE(cdSize, 12);
eocd.writeUInt32LE(localOffset, 16);
eocd.writeUInt16LE(0, 20);

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(zipFile, Buffer.concat([...localChunks, ...cdChunks, eocd]));
const sizeMb = (fs.statSync(zipFile).size / (1024 * 1024)).toFixed(2);
console.log(`\nHandover archive written.`);
console.log(`  File:  ${zipFile}`);
console.log(`  Size:  ${sizeMb} MB`);
console.log(`  Files: ${entries.length}`);
console.log(`\nThe recipient runs: npm install  →  fill js/firebase-config.js  →  npm start`);
